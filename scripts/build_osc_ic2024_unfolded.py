#!/usr/bin/env python3
"""Build the osc_sterile_ic2024_unfolded weight table from the SBND CV MC.

For each IceCube 2024 point (fakedata.calculators.osc_sterile.POINTS):

  1. the SBND nu_mu + nu_mu-bar (CC and NC) spectrum in reco energy
     (nu_E_calo), null and oscillated, the oscillation evaluated at each
     event's own `baseline` branch (metres) and true_E;
  2. the 2D migration matrix N[reco, true] (nu_E_calo vs true_E, cvwgt
     weighted) from the same events;
  3. D'Agostini unfolding (fakedata.unfold, prior = MC truth) of the
     oscillated reco spectrum, N_ITER iterations; the weight per true-energy
     bin is unfolded / null-truth.

The table is hard-coded in fakedata/calculators/osc_sterile.py between the
BEGIN/END UNFOLD TABLE markers. Default: print the diagnostics and the table.

Usage:  ./venv/bin/python scripts/build_osc_ic2024_unfolded.py
            [--input-glob GLOB] [--n-iter 50] [--write | --check]

--write replaces the table in osc_sterile.py; --check exits 1 if the table
there differs from a fresh build (by more than the printed precision).
"""

import argparse
import glob
import os
import re
import sys

import numpy as np
import uproot

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

from fakedata.calculators import osc_sterile                  # noqa: E402
from fakedata.calculators.osc_sterile import POINTS, numu_survival  # noqa: E402
from fakedata.unfold import dagostini, refold                 # noqa: E402

MODULE = os.path.join(REPO, "fakedata", "calculators", "osc_sterile.py")
DEFAULT_GLOB = ("/Users/gputnam/Work/osc/sbn-rewgted-20-sBruce/"
                "sbn-rewgted-20/SBNDMCCV_*_sbruce.root")
BRANCHES = ["nu_E_calo", "true_E", "true_pdg", "baseline", "cvwgt"]
FLAVORS = (14, -14)
# 50: refold closure < 0.75% in every GUMP bin at all three points, and the
# 0.3-1.25 GeV true bins are converged (stable since ~20 iterations). The
# > 1.25 GeV true bins are weakly constrained (nu_E_calo rarely lands above
# 1.25 GeV) and still drift slowly; the 99-event 0-0.3 GeV bin starts to
# fluctuate beyond ~50.
N_ITER = 50

# GUMP signal-box binning (fake-data-reweighter-ana config.GUMP_BINS) with
# open under/overflow bins, so every event lands in a reco bin
GUMP_BINS = [0.3, 0.4, 0.45, 0.5, 0.55, 0.6, 0.65, 0.7, 0.75, 0.8,
             0.85, 0.9, 0.95, 1.0, 1.25, 1.5]
RECO_EDGES = np.array([0.0] + GUMP_BINS + [np.inf])
TRUE_EDGES = np.array([0.0] + GUMP_BINS + [2.0, 3.0, np.inf])

DIGITS = 6
BEGIN = "# BEGIN UNFOLD TABLE"
END = "# END UNFOLD TABLE"


def load(pattern):
    files = sorted(glob.glob(pattern))
    if not files:
        sys.exit(f"no files match {pattern}")
    parts = {b: [] for b in BRANCHES}
    for p in files:
        a = uproot.open(p)["SelectedEvents"].arrays(BRANCHES, library="np")
        for b in BRANCHES:
            parts[b].append(np.asarray(a[b], dtype=np.float64))
    return files, {b: np.concatenate(v) for b, v in parts.items()}


def build(a, n_iter):
    mask = (np.isin(a["true_pdg"], FLAVORS) & (a["true_E"] > 0)
            & (a["baseline"] > 0) & (a["nu_E_calo"] > -900))
    er, et = a["nu_E_calo"][mask], a["true_E"][mask]
    w, l_km = a["cvwgt"][mask], a["baseline"][mask] / 1000.0
    mig, _, _ = np.histogram2d(er, et, [RECO_EDGES, TRUE_EDGES], weights=w)
    null_reco, null_true = mig.sum(axis=1), mig.sum(axis=0)

    res = {}
    for label, (dm2, s22) in POINTS.items():
        p = numu_survival(et, dm2, s22, l_km)
        osc_reco, _ = np.histogram(er, RECO_EDGES, weights=w * p)
        osc_true, _ = np.histogram(et, TRUE_EDGES, weights=w * p)
        iters = dagostini(mig, osc_reco, n_iter)
        res[label] = dict(
            weights=iters[-1] / null_true,
            direct=osc_true / null_true,
            reco_ratio=osc_reco / null_reco,
            closure=[refold(mig, u) / osc_reco - 1 for u in iters])
    info = dict(n_sel=int(mask.sum()), sumw=float(w.sum()),
                null_reco=null_reco, null_true=null_true)
    return res, info


def _fmt_edges(edges):
    return ", ".join("np.inf" if np.isinf(x) else f"{x:g}" for x in edges)


def table_block(res, pattern, files, n_entries, info, n_iter):
    lines = [
        f"{BEGIN} -- generated by scripts/build_osc_ic2024_unfolded.py;",
        "# do not edit by hand (regenerate with --write).",
        f"#   input:  {len(files)} files {os.path.basename(pattern)}",
        f"#           in {os.path.dirname(pattern)}",
        f"#   events: {n_entries} entries, {info['n_sel']} nu_mu/nu_mu-bar "
        f"used, sum(cvwgt) = {info['sumw']:.1f}",
        f"#   reco:   nu_E_calo, edges [{_fmt_edges(RECO_EDGES)}] GeV",
        f"#   D'Agostini iterations: {n_iter}",
        f"UNFOLD_N_ITER = {n_iter}",
        f"UNFOLD_TRUE_EDGES = np.array([{_fmt_edges(TRUE_EDGES)}])",
        "UNFOLD_WEIGHTS = {",
    ]
    for label, r in res.items():
        vals = ", ".join(f"{x:.{DIGITS}f}" for x in r["weights"])
        lines.append(f'    "{label}": np.array([{vals}]),')
    lines += ["}", END]
    return "\n".join(lines) + "\n"


def report(res, info, n_iter):
    np.set_printoptions(linewidth=200, precision=4, suppress=True)
    print(f"selected nu_mu/nu_mu-bar: {info['n_sel']}  "
          f"sum(cvwgt) = {info['sumw']:.1f}")
    print(f"null reco spectrum: {info['null_reco'].round(0)}")
    print(f"null true spectrum: {info['null_true'].round(0)}")
    for label, r in res.items():
        dm2, s22 = POINTS[label]
        print(f"\n== {label}: dm2 = {dm2} eV^2, sin^2(2th) = {s22}")
        print(f"  reco ratio osc/null      : {r['reco_ratio']}")
        print(f"  direct true ratio        : {r['direct']}")
        print(f"  unfolded weight (it {n_iter})  : {r['weights']}")
        for i, c in enumerate(r["closure"], 1):
            inner = c[1:-1]                      # GUMP bins only
            print(f"  refold-1, iter {i}: max |GUMP| = "
                  f"{np.max(np.abs(inner)):.2e}  all bins {c}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--input-glob", default=DEFAULT_GLOB)
    ap.add_argument("--n-iter", type=int, default=N_ITER)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    args = ap.parse_args()

    files, a = load(args.input_glob)
    res, info = build(a, args.n_iter)
    report(res, info, args.n_iter)
    block = table_block(res, args.input_glob, files, len(a["cvwgt"]), info, args.n_iter)

    if args.check:
        bad = []
        if not np.array_equal(osc_sterile.UNFOLD_TRUE_EDGES, TRUE_EDGES):
            bad.append("UNFOLD_TRUE_EDGES")
        if osc_sterile.UNFOLD_N_ITER != args.n_iter:
            bad.append("UNFOLD_N_ITER")
        for label, r in res.items():
            have = osc_sterile.UNFOLD_WEIGHTS.get(label)
            if (have is None or have.shape != r["weights"].shape
                    or np.max(np.abs(have - r["weights"])) > 10 ** -DIGITS):
                bad.append(f"UNFOLD_WEIGHTS[{label}]")
        if bad:
            print(f"\n--check: MISMATCH in {', '.join(bad)}; "
                  f"regenerate with --write")
            return 1
        print("\n--check: table in osc_sterile.py matches a fresh build")
        return 0

    if args.write:
        src = open(MODULE).read()
        pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n",
                         re.S)
        if not pat.search(src):
            sys.exit(f"no {BEGIN} ... {END} block in {MODULE}")
        with open(MODULE, "w") as f:
            f.write(pat.sub(lambda _: block, src, count=1))
        print(f"\nwrote table to {MODULE}")
    else:
        print("\n" + block)
    return 0


if __name__ == "__main__":
    sys.exit(main())
